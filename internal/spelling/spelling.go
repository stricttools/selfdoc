// wordlistFS carries the vendored word list, its retrieval record and
// upstream's copyright notice. All three travel together because the licence
// conditions redistribution of the words on the notice accompanying them.
//
//go:embed wordlist/words.txt wordlist/SOURCE.json wordlist/COPYRIGHT.txt
var wordlistFS embed.FS

// acceptListFilename is the name of the one shared accept list.
const acceptListFilename = "spelling-accept.txt"

// Lookup answers whether a vocabulary accepts a word as written.
//
// It exists so a check run can consult the vendored list, the renderer
// vocabulary and the accept list as one vocabulary without copying 170,000
// entries into a fresh map per document. [Vocab] satisfies it, so every call
// site that holds one set passes it directly.
type Lookup interface {
	// Has reports whether the vocabulary carries word, spelled as given.
	Has(word string) bool
}

// Vocab is a set of words, the Go counterpart of the frozensets the Python
// surface passed around.
type Vocab map[string]struct{}

// Has reports whether the set carries word, spelled as given.
func (v Vocab) Has(word string) bool {
	_, ok := v[word]
	return ok
}

// layered is a Lookup over several vocabularies, consulted in order. It stands
// in for the set unions the Python built per call, without their copy.
type layered []Lookup

// Has reports whether any layer carries word.
func (l layered) Has(word string) bool {
	for _, vocab := range l {
		if vocab != nil && vocab.Has(word) {
			return true
		}
	}
	return false
}

// AcceptListError reports that the accept list exists but cannot be read as
// written.
//
// It is never returned for a missing file -- absence is an empty list. It is
// returned for a line the format does not admit, naming the file, the line
// number and what was wrong with it.
type AcceptListError struct {
	// Message is the whole diagnostic, already naming file and line.
	Message string
}

// Error renders the diagnostic.
func (e *AcceptListError) Error() string { return e.Message }

// Misspelling is one unrecognized word, located precisely enough to open and
// fix.
type Misspelling struct {
	// File is the path named in the diagnostic, as the caller gave it.
	File string
	// Line is the 1-based line the word sits on.
	Line int
	// Column is the 1-based character column in the raw source line.
	Column int
	// Word is the unrecognized word as written.
	Word string
	// Suggestions are the edit-distance-1 neighbours, empty when none were
	// asked for or none were found.
	Suggestions []string
}

// Describe renders the diagnostic message a lint carries.
func (m Misspelling) Describe() string {
	text := fmt.Sprintf("Unrecognized word '%s' (col %d)", m.Word, m.Column)
	if len(m.Suggestions) > 0 {
		text += "; did you mean " + strings.Join(m.Suggestions, ", ") + "?"
	}
	return text
}

// UnknownWord is one unrecognized word located in a single source line.
type UnknownWord struct {
	// Column is the 0-based character offset of the word in the raw line.
	Column int
	// Word is the unrecognized word as written.
	Word string
}

// -- The vocabulary ---------------------------------------------------------

// loadWordlist reads the vendored ESDB word list, exactly as vendored.
var loadWordlist = sync.OnceValue(func() Vocab {
	raw, err := wordlistFS.ReadFile("wordlist/words.txt")
	if err != nil {
		// The file is embedded, so a read failure is a build defect rather
		// than a runtime condition a caller could act on.
		panic("spelling: embedded word list is unreadable: " + err.Error())
	}
	words := Vocab{}
	for _, line := range strings.Split(string(raw), "\n") {
		if line == "" {
			continue
		}
		words[line] = struct{}{}
	}
	return words
})

// LoadWordlist returns the vendored ESDB word list, exactly as vendored.
//
// The list is read and indexed once per process; every later call returns the
// same set.
func LoadWordlist() Vocab { return loadWordlist() }

// WordlistBytes returns the vendored word list's raw bytes, as vendored.
//
// The digest and word count SOURCE.json records describe these bytes, so a
// caller verifying the retrieval record measures what actually ships.
func WordlistBytes() []byte {
	raw, err := wordlistFS.ReadFile("wordlist/words.txt")
	if err != nil {
		panic("spelling: embedded word list is unreadable: " + err.Error())
	}
	return raw
}

// wordlistSource parses the vendored word list's retrieval record.
var wordlistSource = sync.OnceValues(func() (map[string]any, error) {
	raw, err := wordlistFS.ReadFile("wordlist/SOURCE.json")
	if err != nil {
		return nil, err
	}
	var record map[string]any
	if err := json.Unmarshal(raw, &record); err != nil {
		return nil, err
	}
	return record, nil
})

// WordlistSource returns the vendored word list's retrieval record: the URL,
// every generator parameter, the upstream git revisions, the digest and the
// word count.
func WordlistSource() (map[string]any, error) { return wordlistSource() }

// WordlistCopyright returns upstream's copyright notice, verbatim, for
// display. Shipping it beside the words is what the licence conditions
// redistribution on.
func WordlistCopyright() string {
	raw, err := wordlistFS.ReadFile("wordlist/COPYRIGHT.txt")
	if err != nil {
		panic("spelling: embedded copyright notice is unreadable: " + err.Error())
	}
	return string(raw)
}

// AcceptListPath returns the one accept list's path,
// ~/Projects/ark/spelling-accept.txt.
//
// The home directory is resolved per call rather than once at load, so a
// process that changes HOME -- an isolated test run, a sandboxed corpus sweep
// -- reads the list its own environment names.
func AcceptListPath() string {
	home, err := os.UserHomeDir()
	if err != nil {
		// With no home directory there is no shared list; the relative path
		// then simply does not exist, which is an empty accept list.
		return filepath.Join("Projects", "ark", acceptListFilename)
	}
	return filepath.Join(home, "Projects", "ark", acceptListFilename)
}

// acceptEntryRe is the grammar of an accept-list entry: a single word,
// letters, with apostrophes allowed inside contractions and possessives.
// Nothing else, because nothing else could ever be consulted -- the checker
// splits hyphenated compounds into their parts and skips any token carrying a
// digit, so a hyphenated or numeric entry would sit on the list accepting
// nothing.
var acceptEntryRe = regexp.MustCompile(`^` + letterClass + `+(?:['’]` + letterClass + `+)*$`)

// LoadAcceptList reads the accept list at path, or the one [AcceptListPath]
// names when path is empty.
//
// A file that does not exist is an empty list, not an error: a fresh machine
// has simply accepted nothing yet. A file that exists and carries a line the
// format does not admit is an [AcceptListError] naming the line number and the
// reason.
func LoadAcceptList(path string) (Vocab, error) {
	target := path
	if target == "" {
		target = AcceptListPath()
	}
	info, err := os.Stat(target)
	if err != nil || !info.Mode().IsRegular() {
		return Vocab{}, nil
	}
	raw, err := os.ReadFile(target)
	if err != nil {
		return nil, &AcceptListError{
			Message: fmt.Sprintf("%s: %s", target, err),
		}
	}
	accepted := Vocab{}
	for index, line := range strings.Split(string(raw), "\n") {
		entry := strings.TrimSpace(strings.SplitN(line, "#", 2)[0])
		if entry == "" {
			continue
		}
		if !acceptEntryRe.MatchString(entry) {
			return nil, &AcceptListError{Message: fmt.Sprintf(
				"%s:%d: %s is not a single word. An accept-list line holds "+
					"one word (letters, with apostrophes allowed inside it) "+
					"or a '#' comment. Split a hyphenated compound into its "+
					"parts and give each its own line -- the checker checks "+
					"the parts, so a hyphenated entry would accept nothing.",
				target, index+1, util.PythonRepr(entry),
			)}
		}
		accepted[entry] = struct{}{}
	}
	return accepted, nil
}

