// -- Word scanning ----------------------------------------------------------

// letterClass is the character class Python spells `[^\W\d_]`: a word
// character that is neither a decimal digit nor an underscore.
//
// Python's `\w` is every character str.isalnum accepts plus the underscore,
// and `\d` is the decimal digits alone, so subtracting them leaves the
// letters together with the letterlike and other numerals -- Nl and No. A
// superscript two is No, which is why "m²" is one word rather than the word
// "m" beside a character no pattern claims.
const letterClass = `[\p{L}\p{Nl}\p{No}]`

// spaceClass and nonSpaceClass are this package's short spellings of Python's
// Unicode-aware `\s` and `\S`, which Go's own `\s` does not reproduce:
// Python's class carries the C0 separators, the next-line control, and every
// Unicode separator category.
const (
	spaceClass    = util.PythonSpaceClass
	nonSpaceClass = util.PythonNonSpaceClass
)

// attrTokenClass is the character class Python spells `[\w-]`: a Unicode word
// character or a hyphen. Go's own `\w` is ASCII-only, so the class is spelled
// out.
const attrTokenClass = `[\p{L}\p{N}_-]`

// mask is one Markdown or HTML construct whose content is never prose. Each is
// blanked with same-length spaces so every surviving byte keeps its offset,
// and therefore every surviving character keeps its column.
type mask struct {
	// pattern matches the construct.
	pattern *regexp.Regexp
	// wordBoundary is set for a pattern Python anchored with a leading `\b`,
	// which RE2 cannot express Unicode-aware. Such a pattern is anchored at
	// the position being tried and the boundary is checked by hand, retrying
	// one character later on a rejection -- what the regex engine does when a
	// match fails its leading assertion.
	wordBoundary bool
}

// masks are applied in order; each runs over what the previous ones left, so
// the order is part of the behavior.
var masks = []mask{
	// Link and image destinations: the text stays, the URL goes.
	{pattern: regexp.MustCompile(`\]\([^)\n]*\)`)},
	// Reference-style link labels and link-reference definitions.
	{pattern: regexp.MustCompile(`\]\[[^\]\n]*\]`)},
	{pattern: regexp.MustCompile(`(?m)^` + spaceClass + `*\[[^\]\n]+\]:` + spaceClass + `*` + nonSpaceClass + `+`)},
	// HTML tags, comments and autolinks. A tag's attributes are inside it, so
	// the pattern has to admit whitespace -- an earlier form stopped at the
	// first space and let the element name and every attribute value through
	// as prose. The opening character still has to look like the start of a
	// tag (a name, a closing slash, or a "!" declaration), which keeps a
	// comparison written in prose ("x < y and z > 0") out of it. A tag broken
	// across lines is not covered: the scanner is handed one raw source line
	// at a time, so the columns it reports stay true.
	{pattern: regexp.MustCompile(`</?[A-Za-z!][^<>]*>`)},
	// HTML entity references, named and numeric. An entity is markup that
	// renders as one character, so its name is no more a word than a tag's is
	// -- "&nbsp;" is a space, not the word "nbsp".
	{pattern: regexp.MustCompile(`&(?:[A-Za-z][A-Za-z0-9]*|#\p{Nd}+|#[xX][0-9A-Fa-f]+);`)},
	// Bare URLs and mail addresses left loose in prose.
	{pattern: regexp.MustCompile(`^[a-z][a-z0-9+.-]*://` + nonSpaceClass + `+`), wordBoundary: true},
	{pattern: regexp.MustCompile(`^mailto:` + nonSpaceClass + `+`), wordBoundary: true},
	// Directive markers. The inline ":-:" marker and its attributes live
	// inside a paragraph; the block forms are handled by blankBlockMarkers,
	// whose Python spelling used a lookahead RE2 cannot express.
	{pattern: regexp.MustCompile(`:-:` + spaceClass + `+` + attrTokenClass + `+` +
		`(?:` + spaceClass + `+` + attrTokenClass + `+="[^"\n]*")*`)},
}

// blockMarkers are the directive markers that stand alone on a line. Python
// matched them with `^(?::-:|:<:|:@:|:=:|:::|:>:)(?=\s|$)` under MULTILINE.
var blockMarkers = []string{":-:", ":<:", ":@:", ":=:", ":::", ":>:"}

// machineChunkRe matches a whitespace-delimited chunk that is a machine token
// -- an identifier, a path, a version, a qualified name -- rather than
// English. The whole chunk is skipped rather than picked apart, because the
// letters in "os.path" and "max_size" are not words anyone can misspell.
var machineChunkRe = regexp.MustCompile(
	`[0-9_/\\@~^$*]` + // digits and the punctuation identifiers use
		`|::` + // namespace separators
		`|` + letterClass + `\.` + letterClass, // a dot joining two letters
)

// wordRe matches a word: letters, with apostrophes allowed inside and one
// allowed at the end (a plural possessive). Hyphens are separators, not part
// of a word, so a hyphenated compound arrives here already split into parts.
var wordRe = regexp.MustCompile(letterClass + `+(?:['’]` + letterClass + `+)*['’]?`)

// chunkRe splits a masked line into its whitespace-delimited chunks.
var chunkRe = regexp.MustCompile(nonSpaceClass + `+`)

// innerCapitalRe matches an internal case change, which marks camelCase or
// PascalCase: an identifier spelled into prose without backticks. Such a token
// is skipped, because the alternative is flagging every unbackticked symbol
// name in the fleet's documentation.
//
// Two shapes, because a case change has two directions. A capital after a
// lowercase letter is the familiar one ("parseFrontmatter", "TextResponse").
// The other is a run of capitals ending against a capitalized word --
// "JSONResponse", "XMLHttpRequest", "IOError" -- where the acronym and the
// word meet capital-to-capital and there is no lowercase letter before the
// boundary at all. Requiring two capitals in the run keeps an ordinary
// capitalized word out: "Adress" starting a sentence is still a misspelling to
// report.
var innerCapitalRe = regexp.MustCompile(`[a-z][A-Z]|[A-Z]{2}[a-z]`)

// alphabet is the letter set edit-distance-1 candidates are generated over.
const alphabet = "abcdefghijklmnopqrstuvwxyz"

// blank blanks every non-prose construct in line, preserving its byte length
// and therefore every surviving character's column.
func blank(line string) string {
	masked := directives.BlankBacktickSpans(line)
	for _, m := range masks {
		if m.wordBoundary {
			masked = blankBoundaryMatches(masked, m.pattern)
			continue
		}
		masked = blankMatches(masked, m.pattern)
	}
	return blankBlockMarkers(masked)
}

// blankMatches replaces every match of pattern with one space per byte.
func blankMatches(text string, pattern *regexp.Regexp) string {
	locations := pattern.FindAllStringIndex(text, -1)
	if locations == nil {
		return text
	}
	buffer := []byte(text)
	for _, location := range locations {
		blankRange(buffer, location[0], location[1])
	}
	return string(buffer)
}

// blankBoundaryMatches blanks every match of pattern that begins at a word
// boundary, where pattern is anchored at the start of the text it is given.
//
// A match whose preceding character is a word character is rejected and the
// scan retries one character later, which is what a regex engine does when a
// leading `\b` fails: it advances its start position rather than skipping past
// the whole candidate.
func blankBoundaryMatches(text string, pattern *regexp.Regexp) string {
	buffer := []byte(text)
	position := 0
	for position < len(text) {
		location := pattern.FindStringIndex(text[position:])
		if location == nil {
			// Anchored, so no match here means none starting here; step one
			// character on and try again.
			_, width := utf8.DecodeRuneInString(text[position:])
			position += width
			continue
		}
		start, end := position+location[0], position+location[1]
		if wordBoundaryAt(text, start) {
			blankRange(buffer, start, end)
			position = end
			continue
		}
		_, width := utf8.DecodeRuneInString(text[start:])
		position = start + width
	}
	return string(buffer)
}

// wordBoundaryAt reports whether offset in text sits on a word boundary,
// given that the character at offset is itself a word character.
func wordBoundaryAt(text string, offset int) bool {
	if offset == 0 {
		return true
	}
	previous, _ := utf8.DecodeLastRuneInString(text[:offset])
	return !isWordRune(previous)
}

// isWordRune reports whether r is a word character under Python's Unicode
// `\w`: a letter, a number of any kind, or an underscore.
func isWordRune(r rune) bool {
	return r == '_' || unicode.IsLetter(r) || unicode.IsNumber(r)
}

// blankBlockMarkers blanks a directive marker standing at the start of a line
// and followed by whitespace or the end of the text.
func blankBlockMarkers(text string) string {
	buffer := []byte(text)
	for start := 0; start <= len(text); {
		for _, marker := range blockMarkers {
			if !strings.HasPrefix(text[start:], marker) {
				continue
			}
			after := start + len(marker)
			next, _ := utf8.DecodeRuneInString(text[after:])
			if after == len(text) || util.IsPythonSpace(next) {
				blankRange(buffer, start, after)
			}
			break
		}
		newline := strings.IndexByte(text[start:], '\n')
		if newline < 0 {
			break
		}
		start += newline + 1
	}
	return string(buffer)
}

// blankRange overwrites buffer[start:end) with one space per byte.
func blankRange(buffer []byte, start, end int) {
	for i := start; i < end; i++ {
		buffer[i] = ' '
	}
}

// isKnown reports whether vocab holds word in a standard casing form.
//
// Exact first, so an acronym the list carries ("USA", "CPU") is accepted as
// written. Then lowercase, so a capitalized sentence start and an all-caps
// heading are accepted from the ordinary entry.
func isKnown(word string, vocab Lookup) bool {
	return vocab.Has(word) || vocab.Has(strings.ToLower(word))
}

// accepts reports whether word is spelled acceptably against vocab.
func accepts(word string, vocab Lookup) bool {
	if utf8.RuneCountInString(word) < 2 {
		// A lone letter is an enumeration marker or an initial, never a
		// misspelling anyone can act on.
		return true
	}
	if innerCapitalRe.MatchString(word) {
		return true
	}
	if isKnown(word, vocab) {
		return true
	}
	// Possessives: the list carries "dog's" but not every proper noun's.
	for _, suffix := range []string{"'s", "’s", "'", "’"} {
		if !strings.HasSuffix(word, suffix) {
			continue
		}
		base := strings.TrimSuffix(word, suffix)
		if base != "" && isKnown(base, vocab) {
			return true
		}
	}
	return false
}

// SuggestionsFor returns up to limit edit-distance-1 neighbours of word in
// vocab, sorted.
//
// Deliberately cheap: one edit, generated and looked up, no scoring model and
// no distance-2 search. A word with no neighbour gets no suggestion, which is
// a better answer than an expensive wrong one. A word over sixteen characters
// gets none either -- the candidate set grows with its length and the answer
// stops being worth generating.
func SuggestionsFor(word string, vocab Lookup, limit int) []string {
	lowered := strings.ToLower(word)
	runes := []rune(lowered)
	if len(runes) > 16 {
		return nil
	}
	candidates := map[string]struct{}{}
	for index := 0; index <= len(runes); index++ {
		left := string(runes[:index])
		right := runes[index:]
		if len(right) > 0 {
			candidates[left+string(right[1:])] = struct{}{} // delete
			if len(right) > 1 {
				swapped := append([]rune{right[1], right[0]}, right[2:]...)
				candidates[left+string(swapped)] = struct{}{} // swap
			}
			for _, letter := range alphabet {
				candidates[left+string(letter)+string(right[1:])] = struct{}{} // replace
			}
		}
		for _, letter := range alphabet {
			candidates[left+string(letter)+string(right)] = struct{}{} // insert
		}
	}
	delete(candidates, lowered)
	var hits []string
	for candidate := range candidates {
		if vocab.Has(candidate) {
			hits = append(hits, candidate)
		}
	}
	sort.Strings(hits)
	if len(hits) > limit {
		hits = hits[:limit]
	}
	return hits
}

// IterUnknownWords returns every unrecognized word in one raw source line,
// each with its 0-based character offset into that line.
//
// Markers, code spans, URLs and directive syntax are blanked before scanning,
// and machine tokens are skipped whole.
func IterUnknownWords(line string, vocab Lookup) []UnknownWord {
	masked := blank(line)
	var found []UnknownWord
	for _, chunkLocation := range chunkRe.FindAllStringIndex(masked, -1) {
		chunk := masked[chunkLocation[0]:chunkLocation[1]]
		if machineChunkRe.MatchString(chunk) {
			continue
		}
		base := chunkLocation[0]
		for _, wordLocation := range wordRe.FindAllStringIndex(chunk, -1) {
			word := chunk[wordLocation[0]:wordLocation[1]]
			if accepts(word, vocab) {
				continue
			}
			found = append(found, UnknownWord{
				// Blanking preserves byte offsets, so the offset addresses
				// the same byte in the original line; the column a reader
				// wants is that offset in characters.
				Column: utf8.RuneCountInString(line[:base+wordLocation[0]]),
				Word:   word,
			})
		}
	}
	return found
}

// CheckText spell-checks Markdown content, reporting file, line and column.
//
// Structure comes from the block tokenizer: only text-bearing tokens are
// scanned, so fenced code blocks and directive blocks are excluded by
// construction rather than by pattern-matching them back out. Within a token
// the RAW source lines are scanned, not the token's parsed text, so every
// reported column is a real column in the file.
//
// content is a Markdown body with its frontmatter already removed, and file is
// the path to name in each diagnostic. A nil vocab means the vendored word
// list; a nil accepted means the list [AcceptListPath] names, which is where
// the only error this can return comes from. lineOffset is added to every
// reported line, for a body whose frontmatter was stripped. suggest decides
// whether edit-distance-1 suggestions are computed.
//
// The renderer vocabulary is not optional and not machine-local: a page
// selfdoc rendered is checked on machines that have accepted nothing, so it is
// consulted on every run.
func CheckText(
	content string,
	file string,
	vocab Vocab,
	accepted Vocab,
	lineOffset int,
	suggest bool,
) ([]Misspelling, error) {
	words := Lookup(vocab)
	if vocab == nil {
		words = LoadWordlist()
	}
	accept := accepted
	if accepted == nil {
		loaded, err := LoadAcceptList("")
		if err != nil {
			return nil, err
		}
		accept = loaded
	}
	known := layered{words, RendererVocabulary}
	if len(accept) > 0 {
		known = append(known, accept)
	}

	lines := strings.Split(content, "\n")
	var results []Misspelling
	for _, token := range tokenizer.Tokenize(content) {
		if !tokenizer.IsTextBearing(token) {
			continue
		}
		for lineNumber := token.Start(); lineNumber <= token.End(); lineNumber++ {
			if lineNumber < 1 || lineNumber > len(lines) {
				continue
			}
			raw := lines[lineNumber-1]
			for _, unknown := range IterUnknownWords(raw, known) {
				var suggestions []string
				if suggest {
					suggestions = SuggestionsFor(unknown.Word, known, 3)
				}
				results = append(results, Misspelling{
					File:        file,
					Line:        lineNumber + lineOffset,
					Column:      unknown.Column + 1,
					Word:        unknown.Word,
					Suggestions: suggestions,
				})
			}
		}
	}
	return results, nil
}
