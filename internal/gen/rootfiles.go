// rootFileHeaderPrefix is what the first line of every generated root file
// starts with.
//
// It is the whole overwrite check: a file at an output path that does not
// open with it was written by a person, and generating over it would destroy
// work no tool can recover.
const rootFileHeaderPrefix = "<!-- Auto-generated by selfdoc from "

// claudeTemplateBasename is the basename of the root-file template whose
// output Claude Code reads.
const claudeTemplateBasename = "_CLAUDE.md"

// ClaudeOutputRel is the file the _CLAUDE.md template generates, relative to
// the project root. Claude Code loads <project>/.claude/CLAUDE.md as it loads
// a CLAUDE.md at the project root, and under .claude/ the file stays out of
// the project's top level, beside the .claude/settings.json it belongs with.
const ClaudeOutputRel = ".claude/CLAUDE.md"

// PreviousClaudeOutputRel is where selfdoc generated the _CLAUDE.md template
// before it generated ClaudeOutputRel: the project root. A generated file
// still there is moved by `selfdoc layout migrate`, and gen refuses until it
// is.
const PreviousClaudeOutputRel = "CLAUDE.md"

// makeRootFileHeader builds the header comment of a generated root file,
// naming the template it came from so a reader knows where to edit.
func makeRootFileHeader(templatePath string) string {
	return RootFileHeaderLine(templatePath) + "\n\n"
}

// RootFileHeaderLine is the first line of the root file a template generates,
// without its newline: the comment naming the template, so a reader knows
// where to edit.
func RootFileHeaderLine(templatePath string) string {
	return rootFileHeaderPrefix + templatePath + " — do not edit -->"
}

// HasGeneratedHeader reports whether the regular file at path opens with the
// header every generated root file carries, whichever template it names.
func HasGeneratedHeader(path string) bool {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() {
		return false
	}
	return strings.HasPrefix(firstLine(path), rootFileHeaderPrefix)
}

// RootFileOutputName is the file, relative to the project root and spelled
// with forward slashes, a root-file template generates: ClaudeOutputRel for
// the _CLAUDE.md template, and every other template's basename without the
// leading underscore. A basename with no underscore generates nothing and
// answers false.
//
// It is the one place the output path is decided: gen writes there, and the
// version check and the layout migration read there.
func RootFileOutputName(templatePath string) (string, bool) {
	basename := filepath.Base(templatePath)
	if !strings.HasPrefix(basename, "_") {
		return "", false
	}
	if basename == claudeTemplateBasename {
		return ClaudeOutputRel, true
	}
	return basename[1:], true
}

// PreviousClaudeOutputMessage says that a CLAUDE.md an earlier selfdoc
// generated sits at the project root, and names the move: the text gen's
// refusal and check's lint share.
func PreviousClaudeOutputMessage() string {
	return "CLAUDE.md at the repository root was generated by selfdoc, which " +
		"now generates it at " + ClaudeOutputRel + " (Claude Code reads it " +
		"there as it reads a root CLAUDE.md, and would load both). Run " +
		"'selfdoc layout migrate --dry-run' to see the move, then " +
		"'selfdoc layout migrate', which moves it to " + ClaudeOutputRel +
		" and commits."
}

// RefusePreviousClaudeOutput refuses a project whose root CLAUDE.md an
// earlier selfdoc generated, naming the move. A hand-written root CLAUDE.md is
// not selfdoc's, and is left alone.
func RefusePreviousClaudeOutput(baseDir string) error {
	if !HasGeneratedHeader(filepath.Join(baseDir, PreviousClaudeOutputRel)) {
		return nil
	}
	return errors.New("Refusing to generate: " + PreviousClaudeOutputMessage())
}

// gitProbeTimeout bounds each read-only git probe the ignore check makes.
const gitProbeTimeout = 10 * time.Second

// RefuseIgnoredOutput refuses an output path, relative to baseDir and spelled
// with forward slashes, that git ignores: a generated file there could never
// be committed, and the commit that should carry it would pass over it in
// silence. The refusal names the ignore file, its line and its rule, and a
// narrower rule. Outside a git repository nothing is ignored.
func RefuseIgnoredOutput(baseDir, rel string, h *effects.Handle) error {
	probe, err := h.Run(
		[]string{"git", "rev-parse", "--git-dir"},
		effects.Cwd(baseDir), effects.CaptureOutput(),
		effects.Timeout(gitProbeTimeout), effects.Read(),
	)
	if err != nil || probe.ExitCode != 0 {
		return nil
	}
	result, err := h.Run(
		[]string{"git", "check-ignore", "--verbose", "-z", "--stdin"},
		effects.Cwd(baseDir), effects.CaptureOutput(), effects.Stdin([]byte(rel+"\x00")),
		effects.Timeout(gitProbeTimeout), effects.Read(),
	)
	if err != nil {
		return fmt.Errorf("asking git whether it ignores %s: %w", rel, err)
	}
	switch result.ExitCode {
	case 1:
		return nil
	case 0:
	default:
		return fmt.Errorf("asking git whether it ignores %s: git check-ignore exited %d: %s",
			rel, result.ExitCode, strings.TrimSpace(string(result.Stderr)))
	}
	// --verbose -z prints the source, its line, the rule, and the path, each
	// ended by a NUL.
	fields := strings.Split(string(result.Stdout), "\x00")
	if len(fields) < 3 {
		return fmt.Errorf("asking git whether it ignores %s: unexpected git check-ignore output %q",
			rel, result.Stdout)
	}
	source, line, rule := fields[0], fields[1], fields[2]
	if strings.HasPrefix(rule, "!") {
		// A negated rule re-includes the path: it is not ignored.
		return nil
	}
	narrower := "Narrow that rule so it no longer matches " + rel
	if strings.HasPrefix(rel, ".claude/") {
		narrower += ": ignore only what is meant to stay uncommitted, " +
			"for example `.claude/settings.local.json` instead of `.claude/`"
	}
	return fmt.Errorf(
		"Refusing to generate %s: git ignores it, through line %s of %s (`%s`), "+
			"so the generated file could never be committed. %s, and run this again.",
		rel, line, source, rule, narrower)
}

// RootFileOutputPreconditions refuses a project whose root files cannot be
// generated as it stands, before anything is written: a CLAUDE.md an earlier
// selfdoc generated at the project root, or an output path git ignores.
func RootFileOutputPreconditions(config map[string]any, baseDir string, h *effects.Handle) error {
	if err := RefusePreviousClaudeOutput(baseDir); err != nil {
		return err
	}
	for _, templatePath := range configStringList(config, "root_files") {
		outputName, named := RootFileOutputName(templatePath)
		if !named {
			continue
		}
		if err := RefuseIgnoredOutput(baseDir, outputName, h); err != nil {
			return err
		}
	}
	return nil
}

// GenerateRootFiles resolves a project's root-file templates and writes each
// to the path [RootFileOutputName] decides.
//
// config's root_files key lists the templates (paths like
// ".strictmetadata/docs/_README.md"). Each one's basename must start with an
// underscore: _README.md generates README.md at the project root, and
// _CLAUDE.md generates .claude/CLAUDE.md, creating .claude/. The template's
// frontmatter is dropped, its directives are resolved through the project's
// own resolver, and the result is written read-only (0444) under the
// auto-generated header.
//
// Before anything is written, [RootFileOutputPreconditions] refuses a root
// CLAUDE.md an earlier selfdoc generated, and an output path git ignores.
//
// Every directive's attributes are validated BEFORE anything is resolved, so
// an unknown or a missing required attribute is a hard error naming the
// template and the true line in it -- the same refusal selfdoc check makes,
// rather than a page that renders an error marker where its content belongs.
//
// An existing output file whose first line is not the auto-generated header is
// never overwritten: that is a hard error naming the exact header line to add
// in order to adopt the file.
//
// versionOverride, when non-empty, is recorded on config under the runtime
// version-override key, which is what the var directive reads for
// project.version.
//
// It returns the output names, relative to baseDir and spelled with forward
// slashes.
func GenerateRootFiles(config map[string]any, baseDir, versionOverride string, handle *effects.Handle) ([]string, error) {
	if versionOverride != "" {
		config[content.VersionOverrideKey] = versionOverride
	}

	if err := RootFileOutputPreconditions(config, baseDir, handle); err != nil {
		return nil, err
	}
	rootFiles := configStringList(config, "root_files")
	if len(rootFiles) == 0 {
		return nil, nil
	}

	projectResolver, err := resolver.MakeResolver(config, baseDir, handle)
	if err != nil {
		return nil, err
	}
	customNames := customDirectiveNames(config)
	if err := directives.ValidateDirectiveNames(sortedNames(customNames)); err != nil {
		return nil, err
	}
	validNames := catalog.AllBuiltinDirectives()
	for name := range customNames {
		validNames[name] = struct{}{}
	}

	var generated []string

	for _, templatePath := range rootFiles {
		fullTemplate := filepath.Join(baseDir, templatePath)
		if info, err := os.Stat(fullTemplate); err != nil || !info.Mode().IsRegular() {
			return nil, fmt.Errorf("Root file template not found: %s", templatePath)
		}

		outputName, named := RootFileOutputName(templatePath)
		if !named {
			return nil, fmt.Errorf(
				"Root file template basename must start with '_': %s",
				templatePath,
			)
		}
		outputPath := filepath.Join(baseDir, filepath.FromSlash(outputName))

		data, err := os.ReadFile(fullTemplate)
		if err != nil {
			return nil, err
		}

		// The frontmatter is not part of the output. Its line count is
		// needed so an attribute error reports the line in the template
		// file rather than in the stripped body.
		block, err := util.ReadFrontmatter(string(data), templatePath, util.KindPage)
		if err != nil {
			return nil, err
		}
		templateBody, fmLineCount := block.Body, block.Consumed

		// An unknown or missing required attribute is a hard error, before
		// anything is resolved -- mirroring selfdoc check.
		parsed, err := directives.ParseDirectives(templateBody, validNames)
		if err != nil {
			return nil, err
		}
		for _, directive := range parsed {
			if err := catalog.ValidateDirectiveAttrs(
				directive.Name, directive.Attrs,
				templatePath, directive.LineNumber+fmLineCount,
			); err != nil {
				return nil, err
			}
		}

		resolved, err := directives.ResolveDirectives(
			templateBody, projectResolver.Resolve, validNames,
		)
		if err != nil {
			return nil, err
		}

		finalContent := makeRootFileHeader(templatePath) + resolved

		// Overwrite safety: adopt a generated file, refuse a handwritten
		// one.
		if info, err := os.Stat(outputPath); err == nil && info.Mode().IsRegular() {
			if !strings.HasPrefix(firstLine(outputPath), rootFileHeaderPrefix) {
				return nil, errors.New(
					"Refusing to overwrite " + outputPath + ": file exists and " +
						"is not auto-generated by selfdoc. To migrate, add " +
						"'" + strings.TrimRight(makeRootFileHeader(templatePath), " \t\n\r") + "' as " +
						"the first line, or rename the existing file.",
				)
			}
		}

		if err := handle.MkdirAll(filepath.Dir(outputPath)); err != nil {
			return nil, err
		}
		if err := handle.AtomicWrite(outputPath, []byte(finalContent), generatedPageMode); err != nil {
			return nil, err
		}
		generated = append(generated, outputName)
	}

	return generated, nil
}

// firstLine reads the first line of a file, its newline included, and "" when
// the file cannot be read.
func firstLine(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	text := string(data)
	if index := strings.IndexByte(text, '\n'); index >= 0 {
		return text[:index+1]
	}
	return text
}

// customDirectiveNames is the set of directive names a project declares under
// its directives config key.
func customDirectiveNames(config map[string]any) map[string]struct{} {
	names := map[string]struct{}{}
	declared, _ := config["directives"].(map[string]any)
	for name := range declared {
		names[name] = struct{}{}
	}
	return names
}

// sortedNames renders a name set as a sorted slice, so a refusal names the
// same offending directive on every run.
func sortedNames(names map[string]struct{}) []string {
	result := make([]string, 0, len(names))
	for name := range names {
		result = append(result, name)
	}
	sort.Strings(result)
	return result
}

// configStringList reads a list-of-strings config key, skipping any entry that
// is not a string.
func configStringList(config map[string]any, key string) []string {
	raw, _ := config[key].([]any)
	result := make([]string, 0, len(raw))
	for _, item := range raw {
		if value, isString := item.(string); isString {
			result = append(result, value)
		}
	}
	return result
}
