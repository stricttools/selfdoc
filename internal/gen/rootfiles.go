// rootFileHeaderPrefix is what the first line of every generated root file
// starts with.
//
// It is the whole overwrite check: a file at the project root that does not
// open with it was written by a person, and generating over it would destroy
// work no tool can recover.
const rootFileHeaderPrefix = "<!-- Auto-generated by selfdoc from "

// makeRootFileHeader builds the header comment of a generated root file,
// naming the template it came from so a reader knows where to edit.
func makeRootFileHeader(templatePath string) string {
	return "<!-- Auto-generated by selfdoc from " + templatePath +
		" — do not edit -->\n\n"
}

// GenerateRootFiles resolves a project's root-file templates and writes them
// to the project root.
//
// config's root_files key lists the templates (paths like "docs/_CLAUDE.md").
// Each one's basename must start with an underscore, which the output name
// drops: docs/_CLAUDE.md generates CLAUDE.md. The template's frontmatter is
// dropped, its directives are resolved through the project's own resolver,
// and the result is written read-only (0444) under the auto-generated header.
//
// Every directive's attributes are validated BEFORE anything is resolved, so
// an unknown or a missing required attribute is a hard error naming the
// template and the true line in it -- the same refusal selfdoc check makes,
// rather than a page that renders an error marker where its content belongs.
//
// An existing output file whose first line is not the auto-generated header is
// never overwritten: that is a hard error naming the exact header line to add
// in order to adopt the file.
//
// versionOverride, when non-empty, is recorded on config under the runtime
// version-override key, which is what the var directive reads for
// project.version.
//
// It returns the output names, relative to baseDir.
func GenerateRootFiles(config map[string]any, baseDir, versionOverride string, handle *effects.Handle) ([]string, error) {
	if versionOverride != "" {
		config[content.VersionOverrideKey] = versionOverride
	}

	rootFiles := configStringList(config, "root_files")
	if len(rootFiles) == 0 {
		return nil, nil
	}

	projectResolver, err := resolver.MakeResolver(config, baseDir, handle)
	if err != nil {
		return nil, err
	}
	customNames := customDirectiveNames(config)
	if err := directives.ValidateDirectiveNames(sortedNames(customNames)); err != nil {
		return nil, err
	}
	validNames := catalog.AllBuiltinDirectives()
	for name := range customNames {
		validNames[name] = struct{}{}
	}

	var generated []string

	for _, templatePath := range rootFiles {
		fullTemplate := filepath.Join(baseDir, templatePath)
		if info, err := os.Stat(fullTemplate); err != nil || !info.Mode().IsRegular() {
			return nil, fmt.Errorf("Root file template not found: %s", templatePath)
		}

		basename := filepath.Base(templatePath)
		if !strings.HasPrefix(basename, "_") {
			return nil, fmt.Errorf(
				"Root file template basename must start with '_': %s",
				templatePath,
			)
		}
		outputName := basename[1:]
		outputPath := filepath.Join(baseDir, outputName)

		data, err := os.ReadFile(fullTemplate)
		if err != nil {
			return nil, err
		}

		// The frontmatter is not part of the output. Its line count is
		// needed so an attribute error reports the line in the template
		// file rather than in the stripped body.
		block, err := util.ReadFrontmatter(string(data), templatePath, util.KindPage)
		if err != nil {
			return nil, err
		}
		templateBody, fmLineCount := block.Body, block.Consumed

		// An unknown or missing required attribute is a hard error, before
		// anything is resolved -- mirroring selfdoc check.
		parsed, err := directives.ParseDirectives(templateBody, validNames)
		if err != nil {
			return nil, err
		}
		for _, directive := range parsed {
			if err := catalog.ValidateDirectiveAttrs(
				directive.Name, directive.Attrs,
				templatePath, directive.LineNumber+fmLineCount,
			); err != nil {
				return nil, err
			}
		}

		resolved, err := directives.ResolveDirectives(
			templateBody, projectResolver.Resolve, validNames,
		)
		if err != nil {
			return nil, err
		}

		finalContent := makeRootFileHeader(templatePath) + resolved

		// Overwrite safety: adopt a generated file, refuse a handwritten
		// one.
		if info, err := os.Stat(outputPath); err == nil && info.Mode().IsRegular() {
			if !strings.HasPrefix(firstLine(outputPath), rootFileHeaderPrefix) {
				return nil, errors.New(
					"Refusing to overwrite " + outputPath + ": file exists and " +
						"is not auto-generated by selfdoc. To migrate, add " +
						"'" + strings.TrimRight(makeRootFileHeader(templatePath), " \t\n\r") + "' as " +
						"the first line, or rename the existing file.",
				)
			}
		}

		if err := handle.AtomicWrite(outputPath, []byte(finalContent), generatedPageMode); err != nil {
			return nil, err
		}
		generated = append(generated, outputName)
	}

	return generated, nil
}

// firstLine reads the first line of a file, its newline included, and "" when
// the file cannot be read.
func firstLine(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	text := string(data)
	if index := strings.IndexByte(text, '\n'); index >= 0 {
		return text[:index+1]
	}
	return text
}

// customDirectiveNames is the set of directive names a project declares under
// its directives config key.
func customDirectiveNames(config map[string]any) map[string]struct{} {
	names := map[string]struct{}{}
	declared, _ := config["directives"].(map[string]any)
	for name := range declared {
		names[name] = struct{}{}
	}
	return names
}

// sortedNames renders a name set as a sorted slice, so a refusal names the
// same offending directive on every run.
func sortedNames(names map[string]struct{}) []string {
	result := make([]string, 0, len(names))
	for name := range names {
		result = append(result, name)
	}
	sort.Strings(result)
	return result
}

// configStringList reads a list-of-strings config key, skipping any entry that
// is not a string.
func configStringList(config map[string]any, key string) []string {
	raw, _ := config[key].([]any)
	result := make([]string, 0, len(raw))
	for _, item := range raw {
		if value, isString := item.(string); isString {
			result = append(result, value)
		}
	}
	return result
}
