func TestBasicGeneration(t *testing.T) {
	isolate(t)
	requirePython3(t)
	dir, cfg := pythonProject(t)
	result := generate(t, cfg, dir)
	docsDir := genDir(dir)

	t.Run("writes every page it reports", func(t *testing.T) {
		if len(result.Written) == 0 {
			t.Fatal("no pages written")
		}
		for _, name := range result.Written {
			if _, err := os.Stat(filepath.Join(docsDir, name)); err != nil {
				t.Errorf("reported %s but it is not on disk: %v", name, err)
			}
		}
	})

	t.Run("filenames", func(t *testing.T) {
		written := names(result.Written)
		for _, want := range []string{"mylib-core.md", "mylib-utils.md", "mylib.md", "gen-index.md"} {
			if !written[want] {
				t.Errorf("missing %s from %v", want, result.Written)
			}
		}
	})

	t.Run("page content", func(t *testing.T) {
		content := read(t, filepath.Join(docsDir, "mylib-core.md"))
		for _, want := range []string{
			"title = \"mylib.core\"",
			// The module's own docstring seeds the description.
			"Core module.",
			"# mylib.core",
			`:-: ref path="mylib.core" lang="python"`,
			"generated = true",
			`nav_group = "API Reference"`,
			"nav_order =",
			"<!-- generated by selfdoc gen, do not edit -->",
		} {
			if !strings.Contains(content, want) {
				t.Errorf("page does not contain %q:\n%s", want, content)
			}
		}
	})

	t.Run("index frontmatter", func(t *testing.T) {
		content := read(t, filepath.Join(docsDir, "gen-index.md"))
		for _, want := range []string{
			`nav_group = "API Reference"`, "nav_order = 90",
			"# API Reference", "generated = true", "seeded = true",
			"mylib.core", "(../mylib-core/)",
		} {
			if !strings.Contains(content, want) {
				t.Errorf("index does not contain %q:\n%s", want, content)
			}
		}
		if strings.Contains(content, ".html)") {
			t.Errorf("index links to a .html file:\n%s", content)
		}
	})

	t.Run("ref directive of a second page", func(t *testing.T) {
		content := read(t, filepath.Join(docsDir, "mylib-utils.md"))
		if !strings.Contains(content, `:-: ref path="mylib.utils" lang="python"`) {
			t.Errorf("unexpected ref directive:\n%s", content)
		}
	})
}

