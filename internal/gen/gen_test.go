func TestHasGeneratedMarker(t *testing.T) {
	isolate(t)
	dir := t.TempDir()
	cases := []struct {
		name    string
		content string
		want    bool
	}{
		{"declared", "+++\ntitle = \"x\"\ngenerated = true\n+++\nbody\n", true},
		{"absent", "+++\ntitle = \"x\"\n+++\nbody\n", false},
		{"no frontmatter", "generated = true\n", false},
		{"after the closing fence", "+++\ntitle = \"x\"\n+++\ngenerated = true\n", false},
		{"indented", "+++\n  generated = true\n+++\n", true},
		{"false", "+++\ngenerated = false\n+++\n", false},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			path := filepath.Join(dir, testCase.name+".md")
			write(t, path, testCase.content)
			if got := hasGeneratedMarker(path); got != testCase.want {
				t.Errorf("hasGeneratedMarker = %v, want %v", got, testCase.want)
			}
		})
	}

	t.Run("missing file", func(t *testing.T) {
		if hasGeneratedMarker(filepath.Join(dir, "nothing-here.md")) {
			t.Error("a missing file reads as generated")
		}
	})
}

