// rootFileProject is a minimal project that declares root_files, with the
// given extra config keys merged over it.
func rootFileProject(t *testing.T, rootFiles []any, extras map[string]any) (string, map[string]any) {
	t.Helper()
	dir := t.TempDir()
	document := map[string]any{
		"source": []any{map[string]any{"path": "mylib/", "language": "python"}},
		"docs":   "stricttools/docs/",
		"output": "stricttools/.docs-cache/build/",
	}
	if rootFiles != nil {
		document["root_files"] = rootFiles
	}
	for key, value := range extras {
		document[key] = value
	}
	cfg := writeConfig(t, dir, document)
	write(t, filepath.Join(dir, "mylib", "__init__.py"), `"""My library."""`+"\n")
	mkdir(t, filepath.Join(dir, "stricttools", "docs"))
	return dir, cfg
}

// generateRootFiles runs GenerateRootFiles, failing the test on an error.
func generateRootFiles(t *testing.T, cfg map[string]any, dir string) []string {
	t.Helper()
	generated, err := GenerateRootFiles(cfg, dir, "", effects.Unbound())
	if err != nil {
		t.Fatalf("GenerateRootFiles: %v", err)
	}
	return generated
}

func TestRootFilesNoneDeclared(t *testing.T) {
	isolate(t)

	t.Run("no root_files key", func(t *testing.T) {
		dir, cfg := rootFileProject(t, nil, nil)
		if generated := generateRootFiles(t, cfg, dir); len(generated) != 0 {
			t.Errorf("generated %v, want nothing", generated)
		}
	})

	t.Run("an empty root_files list", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{}, nil)
		if generated := generateRootFiles(t, cfg, dir); len(generated) != 0 {
			t.Errorf("generated %v, want nothing", generated)
		}
	})
}

func TestRootFileGeneration(t *testing.T) {
	isolate(t)
	dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
	write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"),
		"+++\ntitle = \"Test\"\n+++\n# Hello\n\nSome text.\n")

	generated := generateRootFiles(t, cfg, dir)

	if len(generated) != 1 || generated[0] != "TEST.md" {
		t.Fatalf("generated %v, want [TEST.md]", generated)
	}
	outputPath := filepath.Join(dir, "TEST.md")
	content := read(t, outputPath)

	if !strings.HasPrefix(content, "<!-- Auto-generated by selfdoc from stricttools/docs/_TEST.md") {
		t.Errorf("the header is missing:\n%s", content)
	}
	if strings.Contains(content, "title = \"Test\"") {
		t.Errorf("the frontmatter was not stripped:\n%s", content)
	}
	for _, want := range []string{"# Hello", "Some text."} {
		if !strings.Contains(content, want) {
			t.Errorf("the body does not contain %q:\n%s", want, content)
		}
	}

	info, err := os.Stat(outputPath)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if got := info.Mode().Perm(); got != 0o444 {
		t.Errorf("mode = %#o, want 0444", got)
	}
}

