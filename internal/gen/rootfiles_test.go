	write(t, filepath.Join(dir, ".strictmetadata", "docs", "_TEST.md"),
		"+++\ntitle = \"Test\"\n+++\nVersion: :-: var key=\"project.version\"\n")

	if _, err := GenerateRootFiles(cfg, dir, "9.9.9", effects.Unbound()); err != nil {
		t.Fatalf("GenerateRootFiles: %v", err)
	}

