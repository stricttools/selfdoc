func TestRootFileRefusesToOverwriteHandwritten(t *testing.T) {
	isolate(t)
	dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
	write(t, filepath.Join(dir, "TEST.md"), "# My hand-written file\n")
	write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"), "# Template\n")

	_, err := GenerateRootFiles(cfg, dir, "", effects.Unbound())
	if err == nil {
		t.Fatal("a hand-written root file was overwritten")
	}
	want := "Refusing to overwrite " + filepath.Join(dir, "TEST.md") +
		": file exists and is not auto-generated by selfdoc. To migrate, add " +
		"'<!-- Auto-generated by selfdoc from stricttools/docs/_TEST.md \u2014 do not edit -->' as " +
		"the first line, or rename the existing file."
	if err.Error() != want {
		t.Errorf("error = %q, want %q", err.Error(), want)
	}
	if content := read(t, filepath.Join(dir, "TEST.md")); content != "# My hand-written file\n" {
		t.Errorf("the hand-written file changed:\n%s", content)
	}
}

func TestRootFileOverwritesGenerated(t *testing.T) {
	isolate(t)
	dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
	outputPath := filepath.Join(dir, "TEST.md")
	write(t, outputPath, "<!-- Auto-generated by selfdoc from stricttools/docs/_TEST.md"+
		" \u2014 do not edit -->\n\n# Old content\n")
	if err := os.Chmod(outputPath, 0o444); err != nil {
		t.Fatalf("chmod: %v", err)
	}
	write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"), "# New content\n")

	generated := generateRootFiles(t, cfg, dir)

	if len(generated) != 1 || generated[0] != "TEST.md" {
		t.Fatalf("generated %v, want [TEST.md]", generated)
	}
	content := read(t, outputPath)
	if !strings.Contains(content, "# New content") {
		t.Errorf("the new content is missing:\n%s", content)
	}
	if strings.Contains(content, "# Old content") {
		t.Errorf("the old content survived:\n%s", content)
	}
}

