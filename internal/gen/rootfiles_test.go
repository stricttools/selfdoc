func TestRootFileDirectiveAttributeEnforcement(t *testing.T) {
	isolate(t)
	requirePython3(t)

	// The template body every case shares, with its own directive spliced
	// in. The frontmatter is there so the reported line number has to be
	// corrected by the frontmatter's own line count.
	template := func(body string) string {
		return "+++\ntitle = \"T\"\n+++\n\n# T\n\n" + body + "\n"
	}

	t.Run("an unknown attribute is a hard error", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
		write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"),
			template(`:-: ref path="mylib" bogus="1"`))

		_, err := GenerateRootFiles(cfg, dir, "", effects.Unbound())
		if err == nil {
			t.Fatal("an unknown attribute was accepted")
		}
		var attrErr *catalog.DirectiveAttrError
		if !errors.As(err, &attrErr) {
			t.Fatalf("error is %T, want a *catalog.DirectiveAttrError: %v", err, err)
		}
		for _, want := range []string{"stricttools/docs/_TEST.md", "bogus"} {
			if !strings.Contains(err.Error(), want) {
				t.Errorf("error %q does not name %q", err.Error(), want)
			}
		}
		if _, statErr := os.Stat(filepath.Join(dir, "TEST.md")); statErr == nil {
			t.Error("the refused template still wrote its output file")
		}
	})

	t.Run("a missing required attribute is a hard error", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
		write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"), template(":-: ref"))

		_, err := GenerateRootFiles(cfg, dir, "", effects.Unbound())
		if err == nil {
			t.Fatal("a missing required attribute was accepted")
		}
		for _, want := range []string{"missing required", "path"} {
			if !strings.Contains(err.Error(), want) {
				t.Errorf("error %q does not name %q", err.Error(), want)
			}
		}
	})

	t.Run("a valid directive resolves", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
		write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"),
			template(`:-: ref path="mylib" lang="python"`))

		generated := generateRootFiles(t, cfg, dir)

		if len(generated) != 1 {
			t.Fatalf("generated %v, want one file", generated)
		}
	})
}

func TestRootFileVarDirectives(t *testing.T) {
	isolate(t)

	cases := []struct {
		name     string
		topology map[string]any
		body     string
		want     string
	}{
		{
			name:     "topology.docs_url",
			topology: map[string]any{"docs_base": "https://docs.smmh.dev", "slug": "mylib"},
			body:     "Docs: :-: var key=\"topology.docs_url\"\n",
			want:     "https://docs.smmh.dev/mylib",
		},
		{
			name:     "topology.posts_url",
			topology: map[string]any{"posts_base": "https://docs.smmh.dev/blog"},
			body:     "Blog: :-: var key=\"topology.posts_url\"\n",
			want:     "https://docs.smmh.dev/blog",
		},
		{
			name:     "topology.slug",
			topology: map[string]any{"slug": "mylib"},
			body:     "Slug: :-: var key=\"topology.slug\"\n",
			want:     "Slug: mylib",
		},
		{
			name:     "an absent topology resolves to nothing",
			topology: nil,
			body:     "Docs: [:-: var key=\"topology.docs_url\"]end\n",
			want:     "[]end",
		},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			extras := map[string]any{}
			if testCase.topology != nil {
				extras["topology"] = testCase.topology
			}
			dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, extras)
			write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"),
				"+++\ntitle = \"Test\"\n+++\n"+testCase.body)

			generateRootFiles(t, cfg, dir)

			content := read(t, filepath.Join(dir, "TEST.md"))
			if !strings.Contains(content, testCase.want) {
				t.Errorf("output does not contain %q:\n%s", testCase.want, content)
			}
		})
	}

	t.Run("several directives in one template", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, map[string]any{
			"topology": map[string]any{
				"docs_base":  "https://docs.smmh.dev",
				"slug":       "mylib",
				"posts_base": "https://docs.smmh.dev/blog",
			},
		})
		write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"), "+++\ntitle = \"Test\"\n+++\n"+
			"# Project\n\n"+
			"Docs: :-: var key=\"topology.docs_url\"\n\n"+
			"Blog: :-: var key=\"topology.posts_url\"\n\n"+
			"Slug: :-: var key=\"topology.slug\"\n")

		generateRootFiles(t, cfg, dir)

		content := read(t, filepath.Join(dir, "TEST.md"))
		for _, want := range []string{
			"https://docs.smmh.dev/mylib", "https://docs.smmh.dev/blog", "Slug: mylib",
		} {
			if !strings.Contains(content, want) {
				t.Errorf("output does not contain %q:\n%s", want, content)
			}
		}
	})

	t.Run("project vars alongside topology vars", func(t *testing.T) {
		dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, map[string]any{
			"topology": map[string]any{"docs_base": "https://docs.smmh.dev", "slug": "mylib"},
		})
		write(t, filepath.Join(dir, "pyproject.toml"),
			"[project]\nname = \"mylib\"\nversion = \"1.0.0\"\n")
		write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"), "+++\ntitle = \"Test\"\n+++\n"+
			"Name: :-: var key=\"project.name\"\n\n"+
			"Docs: :-: var key=\"topology.docs_url\"\n")

		generateRootFiles(t, cfg, dir)

		content := read(t, filepath.Join(dir, "TEST.md"))
		for _, want := range []string{"Name: mylib", "https://docs.smmh.dev/mylib"} {
			if !strings.Contains(content, want) {
				t.Errorf("output does not contain %q:\n%s", want, content)
			}
		}
	})
}

func TestRootFileVersionOverride(t *testing.T) {
	isolate(t)
	dir, cfg := rootFileProject(t, []any{"stricttools/docs/_TEST.md"}, nil)
	write(t, filepath.Join(dir, "pyproject.toml"),
		"[project]\nname = \"mylib\"\nversion = \"1.0.0\"\n")
	write(t, filepath.Join(dir, "stricttools", "docs", "_TEST.md"),
		"+++\ntitle = \"Test\"\n+++\nVersion: :-: var key=\"project.version\"\n")

	if _, err := GenerateRootFiles(cfg, dir, "9.9.9", effects.Unbound()); err != nil {
		t.Fatalf("GenerateRootFiles: %v", err)
	}

	content := read(t, filepath.Join(dir, "TEST.md"))
	if !strings.Contains(content, "Version: 9.9.9") {
		t.Errorf("the override was not used:\n%s", content)
	}
	// The override reaches every later directive resolution through the
	// config object itself, which is how the Python surface passed it.
	if got := cfg["_version_override"]; got != "9.9.9" {
		t.Errorf("config carries %v under the override key, want 9.9.9", got)
	}
}

func TestRootFileTemplatesGenerateInOrder(t *testing.T) {
	isolate(t)
	dir, cfg := rootFileProject(t, []any{"stricttools/docs/_FIRST.md", "stricttools/docs/_SECOND.md"}, nil)
	write(t, filepath.Join(dir, "stricttools", "docs", "_FIRST.md"), "# First\n")
	write(t, filepath.Join(dir, "stricttools", "docs", "_SECOND.md"), "# Second\n")

	generated := generateRootFiles(t, cfg, dir)

	if len(generated) != 2 || generated[0] != "FIRST.md" || generated[1] != "SECOND.md" {
		t.Fatalf("generated %v, want [FIRST.md SECOND.md]", generated)
	}
	for _, name := range generated {
		if !strings.HasPrefix(read(t, filepath.Join(dir, name)), rootFileHeaderPrefix) {
			t.Errorf("%s carries no header", name)
		}
	}
}
