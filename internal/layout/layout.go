// Directory is one function directory selfdoc claims: what it is for, which
// side of the authorship line it sits on, whether the repository commits it,
// and the paths it replaced.
type Directory struct {
	// Name is the directory's function name. The name it carries on disk is
	// [Directory.DiskName].
	Name string
	// Side is whether people or selfdoc write its contents.
	Side Side
	// Commitment is whether the repository carries its contents.
	Commitment Commitment
	// Description says what the directory holds.
	Description string
	// DeprecatedNames are the paths this directory replaced, as they were
	// spelled relative to the repository root. A repository that still has
	// one of them is refused.
	DeprecatedNames []string
}

// declared is the whole claim, in the order a dump prints it.
