// generatedPrefix is what a generated directory's name starts with on disk,
// at the top level of [Root].
const generatedPrefix = "."

// DiskName is the name the directory carries under [Root]: its function name,
// behind a leading dot when selfdoc generates its contents.
func (d Directory) DiskName() string {
	if d.Side == Generated {
		return generatedPrefix + d.Name
	}
	return d.Name
}

// Rel is the directory as a path relative to the repository root, in slash
// form.
func (d Directory) Rel() string {
	return Root + "/" + d.DiskName()
}

// declaredRel is one claimed directory's relative path. It is only ever called
// with the names this package declares, so a miss is a defect in this file.
func declaredRel(name string) string {
	dir, ok := Lookup(name)
	if !ok {
		panic("layout: " + name + " is not a declared directory")
	}
	return dir.Rel()
}

// DiskNameOf is the name a directory carries under [Root]: the derived name
// for a directory selfdoc claims, and the name as given for any other.
func DiskNameOf(name string) string {
	if dir, ok := Lookup(name); ok {
		return dir.DiskName()
	}
	return name
}

// LookupDiskName returns the claimed directory an entry under [Root] is, by
// the name it carries on disk. An entry whose dot disagrees with the claimed
// directory's side is not that directory.
func LookupDiskName(entry string) (Directory, bool) {
	for _, dir := range declared {
		if dir.DiskName() == entry {
			return dir, true
		}
	}
	return Directory{}, false
}

// LookupFunction returns the claimed directory an entry under [Root] names by
// its function, whatever its dot says: the entry with its one leading dot
// removed, when that is a function selfdoc claims.
func LookupFunction(entry string) (Directory, bool) {
	return Lookup(strings.TrimPrefix(entry, generatedPrefix))
}

// Declared returns the directories selfdoc claims, in declaration order.
func Declared() []Directory {
	out := make([]Directory, len(declared))
	copy(out, declared)
	return out
}

// Lookup returns the declaration of one claimed directory.
func Lookup(name string) (Directory, bool) {
	for _, dir := range declared {
		if dir.Name == name {
			return dir, true
		}
	}
	return Directory{}, false
}

// Path joins a repository root with one of this package's slash-form relative
// paths, in the operating system's own spelling.
func Path(baseDir, rel string) string {
	return filepath.Join(baseDir, filepath.FromSlash(rel))
}

// UnderRoot reports whether a declared path names something inside [Root].
// A project may spell its docs and output paths as it likes as long as they
// live in the layout.
func UnderRoot(declaredPath string) bool {
	clean := path.Clean(strings.TrimRight(filepath.ToSlash(declaredPath), "/"))
	return clean == Root || strings.HasPrefix(clean, Root+"/")
}

// EntryOf returns the entry directly under [Root] a relative path sits in, as
// it is spelled on disk.
func EntryOf(rel string) (string, bool) {
	clean := strings.TrimRight(filepath.ToSlash(rel), "/")
	if !strings.HasPrefix(clean, Root+"/") {
		return "", false
	}
	rest := strings.TrimPrefix(clean, Root+"/")
	if rest == "" {
		return "", false
	}
	return strings.SplitN(rest, "/", 2)[0], true
}

// FunctionOf returns the function of the claimed directory a relative path
// sits in. A path under [Root] in a directory selfdoc does not claim, or in
// one whose dot disagrees with the claimed side, sits in none.
func FunctionOf(rel string) (string, bool) {
	entry, ok := EntryOf(rel)
	if !ok {
		return "", false
	}
	dir, claimed := LookupDiskName(entry)
	if !claimed {
		return "", false
	}
	return dir.Name, true
}

// DirectoryManifestRel is a directory's ownership manifest, as a path relative
// to the repository root, in slash form. name is a function name: a directory
// selfdoc claims resolves to the name it carries on disk.
func DirectoryManifestRel(name string) string {
	return entryManifestRel(DiskNameOf(name))
}

// entryManifestRel is the manifest of one entry under [Root], by the name the
// entry carries on disk.
func entryManifestRel(entry string) string {
	return Root + "/" + entry + "/" + ManifestFileName
}

// DirectoryManifestPath is where a directory's ownership manifest sits, in the
// operating system's own spelling.
func DirectoryManifestPath(baseDir, name string) string {
	return Path(baseDir, DirectoryManifestRel(name))
}

// DirectoryManifestContent renders the manifest that declares one tool the
// owner of a directory. Every refusal that asks for a manifest prints from
// here, so the text a person is told to write is generated from the
// declaration rather than typed beside it.
func DirectoryManifestContent(owner string) string {
	return OwnerKey + " = " + strconv.Quote(owner) + "\n"
}

// ReadDirectoryManifest reads and validates one directory's ownership
// manifest.
//
// strictspec is the boundary validator: the file is checked against
// .strictspec/directory-manifest.schema.toml by the generated validator in
// this package, so a manifest that reaches a caller declares an owner and
// nothing else. A missing manifest is returned as the underlying
// [os.ErrNotExist], which callers answer with the file to create.
//
// The schema's format-version gate is supplied here rather than written into
// the file, the way a frontmatter block's is: a manifest on disk is the one
// [OwnerKey] line, and a file that declares the gate itself is refused, so the
// key has exactly one author.
func ReadDirectoryManifest(baseDir, name string) (*DirectoryManifest, error) {
	return readEntryManifest(baseDir, DiskNameOf(name))
}

// readEntryManifest reads and validates the manifest of one entry under
// [Root], named as it is spelled on disk.
func readEntryManifest(baseDir, entry string) (*DirectoryManifest, error) {
	return readManifestFile(Path(baseDir, entryManifestRel(entry)))
}

// readManifestFile reads and validates one ownership manifest by its path.
func readManifestFile(manifestPath string) (*DirectoryManifest, error) {
	raw, err := os.ReadFile(manifestPath)
	if err != nil {
		return nil, err
	}
	if declaresFormatVersion(string(raw)) {
		return nil, fmt.Errorf(
			"%s declares %q, which the reader supplies: remove it, so the manifest is the one %s line",
			manifestPath, formatVersionKey, OwnerKey)
	}
	augmented := string(raw)
	if augmented != "" && !strings.HasSuffix(augmented, "\n") {
		augmented += "\n"
	}
	augmented += fmt.Sprintf("%s = %d\n", formatVersionKey, manifestFormatVersion)
	document, diags := ValidateBytes([]byte(augmented), "toml")
	if len(diags) > 0 {
		var detail strings.Builder
		for _, diagnostic := range diags {
			fmt.Fprintf(&detail, "\n  %s: %s [%s]",
				diagnostic.Path, diagnostic.Message, diagnostic.Code)
		}
		return nil, fmt.Errorf(
			"%s is not a valid ownership manifest. It declares %s and nothing else:%s",
			manifestPath, OwnerKey, detail.String())
	}
	return document, nil
}

// declaresFormatVersion reports whether a manifest's own text assigns the gate
// key that [ReadDirectoryManifest] supplies.
func declaresFormatVersion(text string) bool {
	for _, line := range strings.Split(text, "\n") {
		rest, found := strings.CutPrefix(strings.TrimSpace(line), formatVersionKey)
		if found && strings.HasPrefix(strings.TrimSpace(rest), "=") {
			return true
		}
	}
	return false
}

// SharedOwner is the owner a directory several tools share names in its
// manifest (the options directory and the upstream directory). strictspec
// holds the schemas those directories are validated against, and it is a
// library every reading tool links rather than a command, so no PATH lookup
// can answer for it.
const SharedOwner = "strictspec"

// CLIOwner is the owner the directories a strictcli program's schema and test
// coverage live in name in their manifests (.cli-schema and
// .cli-test-coverage). strictcli is a library its programs link rather than a
// command, so no PATH lookup can answer for it either.
const CLIOwner = "strictcli"

// LibraryOwners are the owners a manifest may name that are libraries rather
// than commands.
var LibraryOwners = []string{SharedOwner, CLIOwner}

// KnownOwner reports whether a manifest names an owner this machine has:
// selfdoc itself, one of [LibraryOwners], or any name PATH answers with an
// executable.
func KnownOwner(owner string) bool {
	if owner == Owner {
		return true
	}
	for _, library := range LibraryOwners {
		if owner == library {
			return true
		}
	}
	_, err := exec.LookPath(owner)
	return err == nil
}

// EnsureOwned answers whether selfdoc may write into one of the directories
// under [Root] in this repository.
//
// The manifest is the permission. A directory carrying none, or one naming
// another tool, is refused -- the first with the file and the line to write,
// which no command but `selfdoc init` writes.
func EnsureOwned(baseDir, name string) error {
	manifest, err := ReadDirectoryManifest(baseDir, name)
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf(
			"selfdoc may not write into %s: it carries no %s, and the manifest is the permission. Create %s holding this line:\n%s",
			Root+"/"+DiskNameOf(name), ManifestFileName, DirectoryManifestRel(name),
			strings.TrimRight(DirectoryManifestContent(Owner), "\n"))
	}
	if err != nil {
		return err
	}
	if manifest.Owner != Owner {
		return fmt.Errorf(
			"selfdoc may not write into %s: %s declares %q as its owner, not %q",
			Root+"/"+DiskNameOf(name), DirectoryManifestRel(name), manifest.Owner, Owner)
	}
	return nil
}

// InitDirectories are the directories `selfdoc init` grants selfdoc: the
// pages, the generated state and the cache every project writes from its first
// build on, and the vocabulary its spell check reads.
var InitDirectories = []string{DocsName, DocsStateName, DocsCacheName, VocabularyName}

// GrantInit writes the ownership manifests of [InitDirectories] that are
// missing, naming selfdoc, and the ignore file of each uncommitted one. It
// returns the slash-form relative paths of the manifests it wrote and of every
// uncommitted directory's ignore file.
//
// It is the adopting act a repository performs by running `selfdoc init`. A
// manifest already naming selfdoc is kept
// as it stands, and one naming another tool refuses the whole grant before
// anything is written: that directory is the other tool's.
func GrantInit(h *effects.Handle, baseDir string) ([]string, error) {
	var missing []string
	for _, name := range InitDirectories {
		manifest, err := ReadDirectoryManifest(baseDir, name)
		switch {
		case errors.Is(err, os.ErrNotExist):
			missing = append(missing, name)
		case err != nil:
			return nil, err
		case manifest.Owner != Owner:
			return nil, fmt.Errorf(
				"selfdoc init may not adopt %s: %s declares %q as its owner, not %q",
				Root+"/"+DiskNameOf(name), DirectoryManifestRel(name), manifest.Owner, Owner)
		}
	}
	written := make([]string, 0, len(missing))
	for _, name := range missing {
		if err := h.MkdirAll(Path(baseDir, declaredRel(name))); err != nil {
			return nil, err
		}
		if err := h.AtomicWrite(DirectoryManifestPath(baseDir, name),
			[]byte(DirectoryManifestContent(Owner)), effects.ModeDefault); err != nil {
			return nil, err
		}
		written = append(written, DirectoryManifestRel(name))
	}
	for _, name := range InitDirectories {
		if dir, _ := Lookup(name); dir.Commitment != Uncommitted {
			continue
		}
		if err := h.MkdirAll(Path(baseDir, declaredRel(name))); err != nil {
			return nil, err
		}
		if err := WriteDirectoryIgnore(h, baseDir, name); err != nil {
			return nil, err
		}
		written = append(written, DirectoryIgnoreRel(name))
	}
	return written, nil
}

// EnsureDir creates a directory inside one of selfdoc's function directories,
// after checking the manifest that permits it, and brings that function
// directory's ignore file up to date when it is uncommitted.
//
// rel is one of this package's slash-form relative paths. Creating anything
// under [Root] goes through here, so no path can reach the filesystem without
// its owning manifest having been read.
func EnsureDir(h *effects.Handle, baseDir, rel string) error {
	entry, ok := EntryOf(rel)
	if !ok {
		return fmt.Errorf("%q is not a path under %s", rel, Root)
	}
	dir, claimed := LookupDiskName(entry)
	if !claimed {
		return fmt.Errorf("selfdoc does not claim %s", Root+"/"+entry)
	}
	name := dir.Name
	if err := EnsureOwned(baseDir, name); err != nil {
		return err
	}
	if err := h.MkdirAll(Path(baseDir, rel)); err != nil {
		return err
	}
	return WriteDirectoryIgnore(h, baseDir, name)
}

// The comments an earlier selfdoc wrapped its block of the ignore file at the
// top of a root in. [WithoutIgnoreBlock] reads them, so a move off that file
// can tell selfdoc's lines from another tool's.
const (
	ignoreBegin = "# BEGIN selfdoc -- derived from selfdoc's layout declaration"
	ignoreEnd   = "# END selfdoc"
)

// directoryIgnoreContent is what the ignore file of an uncommitted directory
// selfdoc owns holds: everything in the directory is ignored except the
// directory's manifest and the ignore file itself. The manifest is the
// permission to write into the directory, and a permission that git did not
// carry would have to be written again in every fresh checkout -- including
// the ones a multi-version build extracts out of git tags.
const directoryIgnoreContent = "# Written by selfdoc from its layout declaration: what this directory holds\n" +
	"# is not committed; its manifest and this file are.\n" +
	"*\n" +
	"!" + IgnoreFileName + "\n" +
	"!" + ManifestFileName + "\n"

// DirectoryIgnoreContent returns what an uncommitted directory's ignore file
// holds.
func DirectoryIgnoreContent() string { return directoryIgnoreContent }

// DirectoryIgnoreRel returns where the ignore file of the directory with the
// given function name sits, relative to the repository root, in slash form.
func DirectoryIgnoreRel(name string) string {
	return declaredRel(name) + "/" + IgnoreFileName
}

// IgnoredDirectories are the directories selfdoc claims whose contents the
// repository does not commit, each of which carries its own ignore file.
func IgnoredDirectories() []Directory {
	var ignored []Directory
	for _, dir := range declared {
		if dir.Commitment == Uncommitted {
			ignored = append(ignored, dir)
		}
	}
	return ignored
}

// WriteDirectoryIgnore brings the ignore file of the directory with the given
// function name up to date, writing nothing when the directory is committed or
// the file already holds what it should.
func WriteDirectoryIgnore(h *effects.Handle, baseDir, name string) error {
	dir, ok := Lookup(name)
	if !ok || dir.Commitment != Uncommitted {
		return nil
	}
	target := Path(baseDir, DirectoryIgnoreRel(name))
	existing, err := os.ReadFile(target)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if string(existing) == directoryIgnoreContent {
		return nil
	}
	return h.AtomicWrite(target, []byte(directoryIgnoreContent), effects.ModeDefault)
}

// RootIgnoreRel is the ignore file an earlier selfdoc derived at the top of
// [Root], which `selfdoc layout migrate` converts into one per directory.
var RootIgnoreRel = Root + "/" + IgnoreFileName

// WithoutIgnoreBlock returns an ignore file's content with selfdoc's block
// removed and every other line kept, for the ignore file a move leaves behind.
func WithoutIgnoreBlock(existing string) string {
	var before, after []string
	inBlock, sawBlock := false, false
	for _, line := range strings.Split(strings.ReplaceAll(existing, "\r\n", "\n"), "\n") {
		switch {
		case strings.TrimSpace(line) == ignoreBegin:
			inBlock, sawBlock = true, true
		case strings.TrimSpace(line) == ignoreEnd:
			inBlock = false
		case inBlock:
		case sawBlock:
			after = append(after, line)
		default:
			before = append(before, line)
		}
	}
	lines := trimBlankEdges(before)
	if rest := trimBlankEdges(after); len(rest) > 0 {
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, rest...)
	}
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

// trimBlankEdges drops the blank lines at both ends of a slice, so joining
// sections never doubles a blank line.
func trimBlankEdges(lines []string) []string {
	start, end := 0, len(lines)
	for start < end && strings.TrimSpace(lines[start]) == "" {
		start++
	}
	for end > start && strings.TrimSpace(lines[end-1]) == "" {
		end--
	}
	return lines[start:end]
}
