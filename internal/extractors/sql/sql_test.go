func TestSymbolDetails(t *testing.T) {
	t.Parallel()

	type wantParam struct {
		name      string
		paramType string
	}

	tests := []struct {
		name             string
		symbol           string
		wantNil          bool
		params           []wantParam
		returnType       string
		returnDocumented bool
	}{
		{
			name:       "a function with a parameter",
			symbol:     "soft_delete",
			params:     []wantParam{{"target_id", "uuid"}},
			returnType: "void",
		},
		{
			name:             "a documented function with no parameters",
			symbol:           "update_timestamp",
			returnType:       "trigger",
			returnDocumented: true,
		},
		{name: "a table is not a function", symbol: "users", wantNil: true},
		{name: "a view is not a function", symbol: "active_users", wantNil: true},
		{name: "a type is not a function", symbol: "status_type", wantNil: true},
		{name: "a name the document does not create", symbol: "missing", wantNil: true},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := writeTree(t, sqlProject())
			got, err := newExtractor().SymbolDetails(
				filepath.Join(root, "sql", "schema.sql"), test.symbol)
			if err != nil {
				t.Fatalf("SymbolDetails: %v", err)
			}
			if test.wantNil {
				if got != nil {
					t.Fatalf("SymbolDetails = %+v, want nothing", got)
				}
				return
			}
			if got == nil {
				t.Fatal("SymbolDetails = nothing, want details")
			}
			if len(got.Params) != len(test.params) {
				t.Fatalf("params = %+v, want %d", got.Params, len(test.params))
			}
			for i, want := range test.params {
				param := got.Params[i]
				if param.Name != want.name {
					t.Errorf("param %d name = %q, want %q", i, param.Name, want.name)
				}
				if want.paramType == "" {
					if param.Type != nil {
						t.Errorf("param %d type = %q, want none", i, *param.Type)
					}
				} else if param.Type == nil || *param.Type != want.paramType {
					t.Errorf("param %d type = %v, want %q", i, param.Type, want.paramType)
				}
				if param.Documented {
					t.Errorf("param %d reported documented; SQL documents no parameters", i)
				}
			}
			if test.returnType == "" {
				if got.ReturnType != nil {
					t.Errorf("return type = %q, want none", *got.ReturnType)
				}
			} else if got.ReturnType == nil || *got.ReturnType != test.returnType {
				t.Errorf("return type = %v, want %q", got.ReturnType, test.returnType)
			}
			if got.ReturnDocumented != test.returnDocumented {
				t.Errorf("return documented = %v, want %v", got.ReturnDocumented, test.returnDocumented)
			}
		})
	}
}

