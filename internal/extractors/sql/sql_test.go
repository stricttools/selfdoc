// writeTree writes a file tree under a fresh temporary directory and answers
// its root.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
	}
	return root
}

// newExtractor builds the extractor under test.
func newExtractor() extractors.Extractor { return New() }

// extract resolves one directive against a fixture root.
func extract(t *testing.T, root, directive string, attrs map[string]string, sourcePaths ...string) string {
	t.Helper()
	out, err := newExtractor().Extract(directive, attrs, nil, sourcePaths, root)
	if err != nil {
		t.Fatalf("extract %s: %v", directive, err)
	}
	return out
}

// schemaSource is the sample document the whole-output tests read: two tables
// with COMMENT ON documentation, two views, an enum and a composite type, and
// two functions, one of them documented.
const schemaSource = `-- Main schema for the application

CREATE TABLE users (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    email text NOT NULL UNIQUE,
    display_name text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    is_active boolean NOT NULL DEFAULT true,
    PRIMARY KEY (id)
);

COMMENT ON TABLE users IS 'Registered user accounts';
COMMENT ON COLUMN users.id IS 'Unique user identifier';
COMMENT ON COLUMN users.email IS 'User email address, must be unique';
COMMENT ON COLUMN users.display_name IS 'Optional display name';

CREATE TABLE posts (
    id bigint GENERATED ALWAYS AS IDENTITY,
    author_id uuid NOT NULL REFERENCES users(id),
    title text NOT NULL,
    body text NOT NULL DEFAULT '',
    view_count integer NOT NULL DEFAULT 0,
    score numeric(10,2),
    tags text[],
    published_at timestamptz,
    CONSTRAINT posts_title_check CHECK (length(title) > 0)
);

COMMENT ON TABLE posts IS 'User-created blog posts';
COMMENT ON COLUMN posts.author_id IS 'Reference to the post author';
COMMENT ON COLUMN posts.tags IS 'Array of tag strings';

CREATE VIEW active_users AS
SELECT id, email, display_name
FROM users
WHERE is_active = true;

CREATE OR REPLACE VIEW recent_posts AS
SELECT p.id, p.title, u.display_name AS author
FROM posts p
JOIN users u ON u.id = p.author_id
WHERE p.published_at > now() - interval '7 days';

CREATE TYPE status_type AS ENUM ('draft', 'published', 'archived');

CREATE TYPE address AS (
    street text,
    city text,
    zip_code text,
    country text
);

CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION soft_delete(target_id uuid)
RETURNS void AS $$
BEGIN
    UPDATE users SET is_active = false WHERE id = target_id;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION update_timestamp IS 'Auto-update timestamp trigger function';
`

